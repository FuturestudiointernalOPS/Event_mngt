import { Injectable } from '@nestjs/common';
import type {
  CreateReportExportRequest,
  ListReportExportsQuery,
  ReportExport,
} from '@event-platform/shared';
import { AppException } from '../../common/app-exception';
import { AUDIT_ACTIONS } from '../../common/audit/audit.actions';
import { AuditService } from '../../common/audit/audit.service';
import type { PaginatedResult } from '../../common/types/authenticated-user';
import { TenantContextService } from '../../database/tenant-context.service';
import { TenantTransactionService } from '../../database/tenant-transaction.service';
import { ReportExportWorker } from './report-export-worker.service';
import {
  EXPORT_CONTENT_TYPES,
  downloadBlocker,
  exportExpiry,
  exportFileName,
} from './report-exports.rules';
import { toReportExport } from './report-exports.mapper';
import { ReportExportsRepository } from './report-exports.repository';

export interface ExportDownload {
  fileName: string;
  contentType: string;
  content: Buffer;
}

/**
 * Report file requests (WP-19).
 *
 * `create` writes a PENDING row and answers immediately; the worker owns generation.
 * The generated bytes live with the row, so a download is a stable snapshot rather than
 * a re-query of data that may have changed since the request.
 */
@Injectable()
export class ReportExportsService {
  constructor(
    private readonly tenantTransaction: TenantTransactionService,
    private readonly tenantContext: TenantContextService,
    private readonly repository: ReportExportsRepository,
    private readonly worker: ReportExportWorker,
    private readonly audit: AuditService,
  ) {}

  async create(
    eventId: string,
    input: CreateReportExportRequest,
  ): Promise<ReportExport> {
    const now = new Date();
    const context = this.tenantContext.getOrThrow();

    const row = await this.tenantTransaction.withTenant(async (tx, tenant) => {
      const event = await this.repository.findEvent(
        tx,
        tenant.organizationId,
        eventId,
      );

      if (!event) {
        throw AppException.notFound('not_found', 'Event not found.');
      }

      return this.repository.create(tx, {
        organizationId: tenant.organizationId,
        eventId,
        requestedByUserId: tenant.userId,
        kind: input.kind,
        format: input.format,
        fileName: exportFileName(event.slug, input.format, now),
        contentType: EXPORT_CONTENT_TYPES[input.format],
        expiresAt: exportExpiry(now),
      });
    });

    await this.audit.record({
      action: AUDIT_ACTIONS.reportExportRequested,
      targetType: 'report_export',
      targetId: row.id,
      metadata: { eventId, format: input.format, kind: input.kind },
    });

    this.worker.enqueue(row.id, context);

    return toReportExport(row);
  }

  list(
    eventId: string,
    query: ListReportExportsQuery,
  ): Promise<PaginatedResult<ReportExport>> {
    return this.tenantTransaction.withTenant(async (tx, tenant) => {
      const event = await this.repository.findEvent(
        tx,
        tenant.organizationId,
        eventId,
      );

      if (!event) {
        throw AppException.notFound('not_found', 'Event not found.');
      }

      const [rows, total] = await this.repository.list(
        tx,
        tenant.organizationId,
        eventId,
        query.status,
        (query.page - 1) * query.pageSize,
        query.pageSize,
      );

      return {
        items: rows.map(toReportExport),
        page: query.page,
        pageSize: query.pageSize,
        total,
      };
    });
  }

  get(exportId: string): Promise<ReportExport> {
    return this.tenantTransaction.withTenant(async (tx, tenant) => {
      const row = await this.repository.find(
        tx,
        tenant.organizationId,
        exportId,
      );

      if (!row) {
        throw AppException.notFound('not_found', 'Export not found.');
      }

      return toReportExport(row);
    });
  }

  download(exportId: string): Promise<ExportDownload> {
    return this.tenantTransaction.withTenant(async (tx, tenant) => {
      const row = await this.repository.findDownload(
        tx,
        tenant.organizationId,
        exportId,
      );

      if (!row) {
        throw AppException.notFound('not_found', 'Export not found.');
      }

      const blocker = downloadBlocker(row.status, row.expiresAt, new Date());

      if (blocker === 'failed') {
        throw AppException.unprocessable(
          'export_failed',
          'The export failed and cannot be downloaded.',
        );
      }

      if (blocker === 'not_ready') {
        throw AppException.conflict(
          'export_not_ready',
          'The export is still being generated.',
        );
      }

      if (blocker === 'expired') {
        throw AppException.gone(
          'export_expired',
          'This export has expired. Request a new one.',
        );
      }

      if (!row.content) {
        throw AppException.conflict(
          'export_not_ready',
          'The export file is not available.',
        );
      }

      return {
        fileName: row.fileName,
        contentType: row.contentType,
        content: Buffer.from(row.content),
      };
    });
  }
}
